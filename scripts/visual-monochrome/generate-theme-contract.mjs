import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const sourcePath = new URL(
  '../../app/src/features/appearance/themeContract.source.json',
  import.meta.url,
);
const generatedPath = new URL(
  '../../app/src/features/appearance/themeContract.generated.ts',
  import.meta.url,
);
const prepaintPath = new URL('../../app/public/theme-prepaint.js', import.meta.url);

const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
const selectableIds = source.selectableThemes.map(({ id }) => id);
const selectableIdSet = new Set(selectableIds);

if (!selectableIdSet.has(source.fallbackTheme)) {
  throw new Error(`Unknown fallback theme: ${source.fallbackTheme}`);
}

for (const [tableName, table] of Object.entries({
  persistedLegacyThemes: source.persistedLegacyThemes,
  syncLegacyThemes: source.syncLegacyThemes,
  commandAliases: source.commandAliases,
})) {
  for (const mappedTheme of Object.values(table)) {
    if (!selectableIdSet.has(mappedTheme)) {
      throw new Error(`${tableName} maps to unknown theme: ${mappedTheme}`);
    }
  }
}

if (Object.keys(source.documentThemes).join('\0') !== selectableIds.join('\0')) {
  throw new Error('documentThemes keys must match selectable theme order');
}

const quote = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const property = (value) => (/^[A-Za-z_$][\w$]*$/.test(value) ? value : quote(value));
const tuple = (values) => `[${values.map(quote).join(', ')}] as const`;
const record = (value) =>
  `{\n${Object.entries(value)
    .map(([key, item]) => `  ${property(key)}: ${quote(item)},`)
    .join('\n')}\n} as const`;

const definitions = `[\n${source.selectableThemes
  .map(
    ({ id, label, description }) =>
      `  { id: ${quote(id)}, label: ${quote(label)}, description: ${quote(description)} },`,
  )
  .join('\n')}\n] as const`;

const generatedTsSource = `/* This file is generated by scripts/visual-monochrome/generate-theme-contract.mjs. */
/* Do not edit by hand. Edit themeContract.source.json and regenerate. */

export const THEME_STORAGE_KEY = ${quote(source.storageKey)};
export const UI_STORE_VERSION = ${source.storeVersion};
export const THEME_FALLBACK_ID = ${quote(source.fallbackTheme)};

export const SELECTABLE_THEME_IDS = ${tuple(selectableIds)};
export type SelectableTheme = (typeof SELECTABLE_THEME_IDS)[number];

export const THEME_DEFINITIONS = ${definitions};
export type ThemeDefinition = (typeof THEME_DEFINITIONS)[number];

export const DOCUMENT_THEME_BY_ID = ${record(source.documentThemes)};
export type ResolvedDocumentTheme =
  (typeof DOCUMENT_THEME_BY_ID)[keyof typeof DOCUMENT_THEME_BY_ID];

export const PERSISTED_LEGACY_THEME_MAP = ${record(source.persistedLegacyThemes)};
export type LegacyPersistedThemeId = keyof typeof PERSISTED_LEGACY_THEME_MAP;

export const SYNC_LEGACY_THEME_MAP = ${record(source.syncLegacyThemes)};

export const THEME_COMMAND_ALIASES = ${record(source.commandAliases)};
`;

const prepaintJsSource = `/* Generated by scripts/visual-monochrome/generate-theme-contract.mjs. */
(() => {
  const selectable = new Set(${JSON.stringify(selectableIds)});
  const legacy = ${JSON.stringify(source.persistedLegacyThemes)};
  const documentThemes = ${JSON.stringify(source.documentThemes)};
  const fallback = ${JSON.stringify(source.fallbackTheme)};
  const root = document.documentElement;
  let preference = fallback;

  try {
    const view = new URLSearchParams(window.location.search).get('view');
    if (view === 'pet-overlay') {
      root.setAttribute('data-vibespace-view', 'pet-overlay');
      root.style.background = 'transparent';
      root.style.backgroundColor = 'transparent';
      root.style.backgroundImage = 'none';
    }
  } catch {
    // Startup must continue even when URL state is unavailable.
  }

  try {
    const payload = JSON.parse(localStorage.getItem(${JSON.stringify(source.storageKey)}) || 'null');
    const value = payload && typeof payload === 'object' && !Array.isArray(payload)
      && payload.state && typeof payload.state === 'object'
      ? payload.state.theme
      : undefined;
    preference = selectable.has(value)
      ? value
      : Object.prototype.hasOwnProperty.call(legacy, value)
        ? legacy[value]
        : fallback;
  } catch {
    preference = fallback;
  }

  root.setAttribute('data-theme', documentThemes[preference]);
  root.setAttribute('data-theme-preference', preference);
})();
`;

const prettierConfig = (await resolveConfig(fileURLToPath(prepaintPath))) ?? {};
const generatedTs = await format(generatedTsSource, {
  ...prettierConfig,
  parser: 'typescript',
});
const prepaintJs = await format(prepaintJsSource, {
  ...prettierConfig,
  parser: 'babel',
});

const canonicalText = (value) => value.replace(/\r\n?/g, '\n');

const outputs = [
  [generatedPath, generatedTs],
  [prepaintPath, prepaintJs],
];

if (process.argv.includes('--check')) {
  const stale = outputs
    .filter(([path, expected]) => {
      try {
        return canonicalText(readFileSync(path, 'utf8')) !== canonicalText(expected);
      } catch {
        return true;
      }
    })
    .map(([path]) => fileURLToPath(path));

  if (stale.length > 0) {
    console.error(`Generated theme contract is stale:\n${stale.join('\n')}`);
    process.exitCode = 1;
  }
} else {
  for (const [path, contents] of outputs) {
    writeFileSync(path, contents);
  }
}
