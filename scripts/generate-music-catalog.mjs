import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function musicDisplayName(filename) {
  return filename.replace(extname(filename), '').replace(/^ES_/i, '').trim();
}

export function musicSlug(filename) {
  return musicDisplayName(filename)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 72);
}

export async function sha256File(filePath) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(filePath)) hash.update(chunk);
  return hash.digest('hex');
}

export async function buildMusicManifest(inputDir, generatedAt = new Date().toISOString()) {
  const root = resolve(inputDir);
  if (!existsSync(root)) throw new Error(`music_input_missing:${root}`);
  const names = readdirSync(root)
    .filter((name) => extname(name).toLowerCase() === '.mp3')
    .sort((left, right) => left.localeCompare(right, 'en', { sensitivity: 'base' }));
  if (names.length === 0) throw new Error('music_input_empty');

  const tracks = [];
  for (const [index, sourceName] of names.entries()) {
    if (sourceName.includes('/') || sourceName.includes('\\')) throw new Error('unsafe_music_name');
    const sourcePath = join(root, sourceName);
    const sha256 = await sha256File(sourcePath);
    const id = `music-${String(index + 1).padStart(3, '0')}-${sha256.slice(0, 12)}`;
    tracks.push({
      id,
      name: musicDisplayName(sourceName),
      sourceName,
      objectKey: `tracks/${id}-${musicSlug(sourceName) || 'track'}.mp3`,
      bytes: statSync(sourcePath).size,
      sha256,
      contentType: 'audio/mpeg',
    });
  }
  return {
    version: 1,
    generatedAt,
    count: tracks.length,
    totalBytes: tracks.reduce((total, track) => total + track.bytes, 0),
    tracks,
  };
}

export function renderMusicCatalogModule(manifest) {
  const tracks = manifest.tracks.map(({ sourceName: _sourceName, ...track }) => track);
  return `/* Auto-generated by scripts/generate-music-catalog.mjs — metadata only. */\nexport const MUSIC_LIBRARY_VERSION = ${JSON.stringify(manifest.version)};\nexport const MUSIC_LIBRARY_TOTAL_BYTES = ${JSON.stringify(manifest.totalBytes)};\nexport const MUSIC_LIBRARY_TRACKS = ${JSON.stringify(tracks, null, 2)} as const;\n`;
}

async function main() {
  const inputIndex = process.argv.indexOf('--input');
  const outputIndex = process.argv.indexOf('--output');
  const tsOutputIndex = process.argv.indexOf('--ts-output');
  const input = inputIndex >= 0 ? process.argv[inputIndex + 1] : null;
  const output = outputIndex >= 0 ? process.argv[outputIndex + 1] : null;
  const tsOutput = tsOutputIndex >= 0 ? process.argv[tsOutputIndex + 1] : null;
  if (!input || !output) throw new Error('usage: --input <directory> --output <manifest>');
  const manifest = await buildMusicManifest(input);
  writeFileSync(resolve(output), `${JSON.stringify(manifest, null, 2)}\n`);
  if (tsOutput) writeFileSync(resolve(tsOutput), renderMusicCatalogModule(manifest));
  console.log(`Generated ${manifest.count} tracks (${manifest.totalBytes} bytes).`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
