import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';

export function slugifyWallpaperFile(name) {
  return name
    .replace(extname(name), '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);
}

export async function sha256File(path) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest('hex');
}

export function parseCatalogSeed(source) {
  const match = source.match(/CATALOG_SEED:[^=]+=(\s*\[[\s\S]*\])\s+as unknown/);
  if (!match) throw new Error('catalog_seed_parse_failed');
  return JSON.parse(match[1]);
}

export async function buildMasterManifest({ inputDir, catalog }) {
  if (!existsSync(inputDir)) throw new Error(`wallpaper_input_missing:${inputDir}`);
  const bySlug = new Map(
    readdirSync(inputDir)
      .filter((name) => extname(name).toLowerCase() === '.mp4')
      .map((name) => [slugifyWallpaperFile(name), name]),
  );
  if (bySlug.size !== catalog.length) {
    throw new Error(`wallpaper_count_mismatch:catalog=${catalog.length}:source=${bySlug.size}`);
  }

  const objects = [];
  for (const wallpaper of catalog) {
    const sourceName = bySlug.get(wallpaper.slug);
    if (!sourceName) throw new Error(`wallpaper_source_missing:${wallpaper.slug}`);
    const sourcePath = join(inputDir, sourceName);
    const sizeBytes = statSync(sourcePath).size;
    if (sizeBytes !== wallpaper.size_bytes) {
      throw new Error(
        `wallpaper_size_mismatch:${wallpaper.slug}:catalog=${wallpaper.size_bytes}:source=${sizeBytes}`,
      );
    }
    objects.push({
      id: wallpaper.id,
      slug: wallpaper.slug,
      sourceName,
      sourcePath,
      storagePath: `wallpapers/${wallpaper.slug}/wallpaper.mp4`,
      sizeBytes,
      sha256: await sha256File(sourcePath),
      contentType: 'video/mp4',
    });
  }
  return {
    version: 1,
    generatedAt: new Date().toISOString(),
    inputDir: resolve(inputDir),
    count: objects.length,
    totalBytes: objects.reduce((sum, item) => sum + item.sizeBytes, 0),
    objects,
  };
}

export function hydrateVerifiedManifest({ inputDir, manifest }) {
  const root = resolve(inputDir);
  if (manifest.count !== manifest.objects?.length || manifest.count < 1) {
    throw new Error('verified_manifest_invalid');
  }
  const objects = manifest.objects.map((item) => {
    if (basename(item.sourceName) !== item.sourceName) {
      throw new Error(`verified_manifest_source_unsafe:${item.slug}`);
    }
    const sourcePath = resolve(root, item.sourceName);
    if (!sourcePath.startsWith(`${root}\\`) && !sourcePath.startsWith(`${root}/`)) {
      throw new Error(`verified_manifest_source_unsafe:${item.slug}`);
    }
    const sizeBytes = statSync(sourcePath).size;
    if (sizeBytes !== item.sizeBytes || !/^[0-9a-f]{64}$/.test(item.sha256)) {
      throw new Error(`verified_manifest_object_changed:${item.slug}`);
    }
    return { ...item, sourcePath };
  });
  return { ...manifest, inputDir: root, objects };
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function renderCatalogSeed(catalog, manifest) {
  const hashes = new Map(manifest.objects.map((item) => [item.slug, item.sha256]));
  const updated = catalog.map((wallpaper) => ({
    ...wallpaper,
    sha256: hashes.get(wallpaper.slug) ?? wallpaper.sha256,
  }));
  return (
    `/* Auto-generated by scripts/prepare-wallpaper-assets.mjs — metadata only */\n` +
    `import type { CatalogWallpaper } from './types';\n` +
    `/* prettier-ignore */\n` +
    `export const CATALOG_SEED: CatalogWallpaper[] = ${JSON.stringify(updated, null, 2)} as unknown as CatalogWallpaper[];\n`
  );
}

export function renderActivationMigration(schemaSql, catalog, manifest) {
  const objects = new Map(manifest.objects.map((item) => [item.slug, item]));
  const seed = catalog
    .map((wallpaper) => {
      const object = objects.get(wallpaper.slug);
      if (!object) throw new Error(`manifest_object_missing:${wallpaper.slug}`);
      return `insert into public.wallpapers (id, slug, name, description, category, tags, version, author, storage_path, thumbnail_path, preview_path, fallback_path, size_bytes, width, height, format, engine_type, sha256, performance_tier, featured, active, sort_order) values (${sqlString(wallpaper.id)}::uuid, ${sqlString(wallpaper.slug)}, ${sqlString(wallpaper.name)}, ${sqlString(wallpaper.description)}, ${sqlString(wallpaper.category)}, array[${wallpaper.tags.map(sqlString).join(',')}], ${sqlString(wallpaper.version)}, ${sqlString(wallpaper.author)}, ${sqlString(object.storagePath)}, ${sqlString(wallpaper.thumbnail_path)}, ${sqlString(wallpaper.preview_path)}, ${sqlString(wallpaper.fallback_path)}, ${object.sizeBytes}, ${wallpaper.width}, ${wallpaper.height}, ${sqlString(wallpaper.format)}, ${sqlString(wallpaper.engine_type)}, ${sqlString(object.sha256)}, ${sqlString(wallpaper.performance_tier)}, ${wallpaper.featured}, true, ${wallpaper.sort_order}) on conflict (slug) do update set name = excluded.name, description = excluded.description, category = excluded.category, tags = excluded.tags, storage_path = excluded.storage_path, thumbnail_path = excluded.thumbnail_path, preview_path = excluded.preview_path, fallback_path = excluded.fallback_path, size_bytes = excluded.size_bytes, sha256 = excluded.sha256, active = true, updated_at = now();`;
    })
    .join('\n');
  return `${schemaSql.trim()}\n\n-- R2 master catalog activation: full-content hashes and private object keys.\n${seed}\n`;
}

function argument(name, fallback = null) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : (process.argv[index + 1] ?? fallback);
}

function uploadObject(bucket, item) {
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const windowsNpxCli = join(
      dirname(process.execPath),
      'node_modules',
      'npm',
      'bin',
      'npx-cli.js',
    );
    const command = process.platform === 'win32' ? process.execPath : 'npx';
    const commandPrefix = process.platform === 'win32' ? [windowsNpxCli] : [];
    const result = spawnSync(
      command,
      [
        ...commandPrefix,
        '--yes',
        'wrangler@latest',
        'r2',
        'object',
        'put',
        `${bucket}/${item.storagePath}`,
        '--file',
        item.sourcePath,
        '--content-type',
        item.contentType,
        '--cache-control',
        'private, no-store',
        '--remote',
        '--force',
      ],
      { stdio: 'inherit' },
    );
    if (result.status === 0) return;
    if (attempt === 3) throw new Error(`r2_upload_failed:${item.slug}`);
  }
}

async function main() {
  const root = resolve(import.meta.dirname, '..');
  const inputDir = argument('--input');
  if (!inputDir) throw new Error('missing_--input');
  const manifestPath = join(root, 'scripts/wallpaper-master-manifest.generated.json');
  if (process.argv.includes('--resume-upload')) {
    const saved = JSON.parse(
      await import('node:fs/promises').then((fs) => fs.readFile(manifestPath, 'utf8')),
    );
    const manifest = hydrateVerifiedManifest({ inputDir, manifest: saved });
    const bucket = argument('--bucket', 'vibespace-wallpapers-free');
    for (const item of manifest.objects) uploadObject(bucket, item);
    console.log(
      `Uploaded ${manifest.count} verified wallpaper masters (${manifest.totalBytes} bytes).`,
    );
    return;
  }
  const catalogPath = join(root, 'app/src/features/wallpaper-library/catalogSeed.generated.ts');
  const catalogSource = await import('node:fs/promises').then((fs) =>
    fs.readFile(catalogPath, 'utf8'),
  );
  let catalog;
  try {
    catalog = parseCatalogSeed(catalogSource);
  } catch (error) {
    // Node 22+ can safely strip types from this local generated module. This one-time
    // compatibility path lets the tool recover a seed that a formatter rewrote.
    if (Number(process.versions.node.split('.')[0]) < 22) throw error;
    catalog = (await import(`${pathToFileURL(catalogPath).href}?catalog=${Date.now()}`))
      .CATALOG_SEED;
  }
  const manifest = await buildMasterManifest({ inputDir, catalog });
  const committedManifest = {
    version: manifest.version,
    generatedAt: manifest.generatedAt,
    count: manifest.count,
    totalBytes: manifest.totalBytes,
    objects: manifest.objects.map(({ sourcePath: _sourcePath, ...item }) => item),
  };
  writeFileSync(manifestPath, `${JSON.stringify(committedManifest, null, 2)}\n`);

  if (process.argv.includes('--write-catalog')) {
    writeFileSync(catalogPath, renderCatalogSeed(catalog, manifest));
  }
  if (process.argv.includes('--write-migration')) {
    const schemaPath = join(root, 'supabase/migrations/0031_wallpapers.sql');
    const schemaSql = await import('node:fs/promises').then((fs) =>
      fs.readFile(schemaPath, 'utf8'),
    );
    writeFileSync(
      join(root, 'supabase/migrations/0048_wallpaper_r2_catalog_activation.sql'),
      renderActivationMigration(schemaSql, catalog, manifest),
    );
  }
  if (process.argv.includes('--upload')) {
    const bucket = argument('--bucket', 'vibespace-wallpapers-free');
    for (const item of manifest.objects) uploadObject(bucket, item);
  }
  console.log(
    `Verified ${manifest.count} wallpaper masters (${manifest.totalBytes} bytes) with full SHA-256.`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : 'wallpaper_upload_failed');
    process.exitCode = 1;
  });
}
